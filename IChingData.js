function getTrigramByBits(bitArray) {
  if (!bitArray || bitArray.length < 3) return null;
  for (var name in TRIGRAMS) {
    var t = TRIGRAMS[name];
    if (t.lines[0] === bitArray[0] && t.lines[1] === bitArray[1] && t.lines[2] === bitArray[2]) {
      return t;
    }
  }
  return null;
}

function resolveTrigram(threeLines) {
  if (!threeLines || threeLines.length < 3) return null;
  var pBits = [threeLines[0].primaryBit, threeLines[1].primaryBit, threeLines[2].primaryBit];
  var primary = getTrigramByBits(pBits);
  var cBits = [threeLines[0].changedBit, threeLines[1].changedBit, threeLines[2].changedBit];
  var transformed = getTrigramByBits(cBits);
  var hasChanging = threeLines[0].isChanging || threeLines[1].isChanging || threeLines[2].isChanging;
  return {
    primary: primary,
    transformed: hasChanging ? transformed : null,
    hasChanging: hasChanging
  };
}

function getHexagramByBits(bitArray) {
  var binStr = "";
  for (var i = 0; i < bitArray.length; i++) {
    binStr += String(bitArray[i]);
  }
  return BY_BINARY[binStr] || null;
}

function getHexagramByNumber(num) {
  for (var i = 0; i < HEXAGRAMS.length; i++) {
    if (HEXAGRAMS[i].number === num) return HEXAGRAMS[i];
  }
  return null;
}

function resolveConsultation(lines) {
  if (!lines || lines.length !== 6) return null;
  
  var primaryBits = [];
  var changedBits = [];
  var changingLineNumbers = [];

  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    primaryBits.push(line.primaryBit);
    changedBits.push(line.changedBit);
    if (line.isChanging) {
      changingLineNumbers.push(line.lineNumber);
    }
  }

  var primaryHex = getHexagramByBits(primaryBits);
  var changedHex = null;
  
  if (changingLineNumbers.length > 0) {
    changedHex = getHexagramByBits(changedBits);
  }

  return {
    primary: primaryHex,
    transformed: changedHex,
    hasChangingLines: changingLineNumbers.length > 0,
    changingLines: changingLineNumbers,
    lines: lines
  };
}
